import hashlib
import json
import re
import sys
import urllib.error
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OFFERS = ROOT / "offers.ts"
STATE = ROOT / ".offer-monitor-state.json"
ALERTS = ROOT / "source-status.js"
USER_AGENT = "FeiraBoaOfferMonitor/1.0 (official public flyer change detection)"


def main():
    urls = sorted(set(re.findall(r'sourceUrl:\s*"(https?://[^\"]+)"', OFFERS.read_text(encoding="utf-8"))))
    old_state = json.loads(STATE.read_text(encoding="utf-8")) if STATE.exists() else {}
    new_state = dict(old_state)
    alerts = []
    checked_at = datetime.now(timezone.utc).date().isoformat()

    for url in urls:
        request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
        try:
            with urllib.request.urlopen(request, timeout=30) as response:
                body = response.read()
                status = response.status
                content_type = response.headers.get("Content-Type", "")
                final_url = response.geturl()
            digest = hashlib.sha256(body).hexdigest()
            previous = old_state.get(url, {}).get("sha256")
            changed = previous is not None and previous != digest
            pending = old_state.get(url, {}).get("needs_review", False) or changed
            new_state[url] = {
                "sha256": digest,
                "status": status,
                "content_type": content_type,
                "final_url": final_url,
                "checked_at": checked_at,
                # Date precision keeps push-triggered workflow runs idempotent on the same UTC day.
                "last_success_at": checked_at,
                "last_error": None,
                "needs_review": pending,
            }
            if pending:
                alerts.append({"url": url, "message": "Official source changed; offer details need verification."})
            print(f"OK {status} {url}" + (" [CHANGED]" if changed else ""))
        except (urllib.error.URLError, TimeoutError, OSError) as error:
            print(f"WARN {url}: {error}")
            previous_state = old_state.get(url, {})
            new_state[url] = {
                **previous_state,
                "checked_at": checked_at,
                "last_error": type(error).__name__,
                "needs_review": previous_state.get("needs_review", False),
            }
            if previous_state.get("needs_review"):
                alerts.append({"url": url, "message": "Official source changed; offer details need verification."})

    STATE.write_text(json.dumps(new_state, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    statuses = {
        url: {
            "checkedAt": state.get("checked_at"),
            "lastSuccessAt": state.get("last_success_at"),
            "error": bool(state.get("last_error")),
            "needsReview": bool(state.get("needs_review")),
        }
        for url, state in new_state.items()
        if url in urls
    }
    generated = (
        "// Generated by scripts/monitor_sources.py.\n"
        "window.FEIRA_SOURCE_STATUS = " + json.dumps(statuses, ensure_ascii=False) + ";\n"
        "window.FEIRA_SOURCE_ALERTS = " + json.dumps(alerts, ensure_ascii=False) + ";\n"
    )
    ALERTS.write_text(generated, encoding="utf-8")
    if len(new_state) != len(urls):
        print("Some sources have not been fetched yet; check the warnings above.")
    failed = sum(1 for url in urls if new_state.get(url, {}).get("last_error"))
    print(f"Checked {len(urls)} official offer source(s); {failed} failed; {len(alerts)} changed.")


if __name__ == "__main__":
    main()
