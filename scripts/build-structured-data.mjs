import { readFile, writeFile } from "node:fs/promises";

const feed = JSON.parse(await readFile(new URL("../offers.json", import.meta.url), "utf8"));
const baseUrl = "https://feira-boa.pages.dev/";
const today = new Intl.DateTimeFormat("en-CA", {
  timeZone: "America/Sao_Paulo",
  year: "numeric",
  month: "2-digit",
  day: "2-digit",
}).format(new Date());

const active = feed.offers
  .filter((offer) => offer.validFrom <= today && offer.validTo >= today)
  .sort((a, b) => a.price - b.price)
  .slice(0, 30);

const data = {
  "@context": "https://schema.org",
  "@type": "ItemList",
  name: "Ofertas da Feira Boa",
  description: "Ofertas de supermercados em São João da Boa Vista.",
  numberOfItems: active.length,
  itemListElement: active.map((offer, index) => ({
    "@type": "ListItem",
    position: index + 1,
    item: {
      "@type": "Product",
      name: offer.name,
      category: offer.productType,
      brand: offer.brand || undefined,
      offers: {
        "@type": "Offer",
        price: offer.price.toFixed(2),
        priceCurrency: "BRL",
        availability: "https://schema.org/InStock",
        url: `${baseUrl}index.html?offer=${encodeURIComponent(offer.id)}`,
        priceValidUntil: offer.validTo,
        seller: { "@type": "Store", name: offer.store },
      },
    },
  })),
};

const script = "// Generated by scripts/build-structured-data.mjs.\n"
  + "(() => {\n"
  + "  const data = " + JSON.stringify(data) + ";\n"
  + "  const script = document.createElement(\"script\");\n"
  + "  script.type = \"application/ld+json\";\n"
  + "  script.textContent = JSON.stringify(data);\n"
  + "  document.head.append(script);\n"
  + "})();\n";
await writeFile(new URL("../offers-jsonld.js", import.meta.url), script, "utf8");
console.log(`Generated offers-jsonld.js with ${active.length} offers.`);
